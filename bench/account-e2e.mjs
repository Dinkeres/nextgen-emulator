// Account flow against a LOCAL copy of the Horizon account server (never the live one):
//   cd <copy of horizon/web/backend> && wrangler dev --local --port 8799   (ALLOWED_ORIGINS=http://localhost:4173)
import { chromium } from 'playwright';
const LIVE = 'https://horizon-test.luvrookie1.workers.dev', LOCAL = process.env.ACCOUNT_LOCAL ?? 'http://127.0.0.1:8799';
const b = await chromium.launch();
const ctx = await b.newContext();
await ctx.route(LIVE + '/**', async r => r.fulfill({ response: await r.fetch({ url: r.request().url().replace(LIVE, LOCAL) }) }));
const p = await ctx.newPage();
p.on('pageerror', e => console.log('PAGE ERROR', e.message));
const ok = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) process.exitCode = 1; };
await p.goto('http://localhost:4173/');
await p.click('text=Get started');
await p.click('text=Sign in');
const u = 'tester_' + (Date.now() % 1e6);
await p.click('button.chip:has-text("Create account")');
await p.fill('input[aria-label="Email"]', u + '@example.test');
await p.fill('input[aria-label="Username"]', u);
await p.fill('input[aria-label="Password"]', 'short');
await p.click('form button[type=submit]');
ok(await p.isVisible('text=at least 8 characters'), 'short password rejected before sending');
await p.fill('input[aria-label="Password"]', 'correct horse battery');
await p.click('form button[type=submit]');
await p.waitForSelector('text=Sign out');
ok(await p.isVisible(`text=${u}`), 'signed up and signed in');
ok(!JSON.stringify(await p.evaluate(() => ({ ...localStorage }))).includes('correct horse'), 'password not stored in the browser');
await p.reload(); await p.goBack().catch(() => {});
await p.goto('http://localhost:4173/');
ok(await p.waitForSelector(`button:has-text("${u}")`, { timeout: 8000 }).then(() => true, () => false), 'still signed in after reload (header shows name)');
await p.click(`button:has-text("${u}")`);
await p.click('text=Sign out');
await p.fill('input[aria-label="Email"]', u + '@example.test');
await p.fill('input[aria-label="Password"]', 'wrong password!');
await p.click('form button[type=submit]');
ok(await p.waitForSelector('text=Wrong email or password', { timeout: 8000 }).then(() => true, () => false), 'wrong password shows an error');
await p.fill('input[aria-label="Password"]', 'correct horse battery');
await p.click('form button[type=submit]');
await p.waitForSelector('text=Sign out');
await p.goto('http://localhost:4173/');
await p.click('button[aria-label="Multiplayer"]');
ok(await p.isVisible(`text=Playing as ${u}`), 'lobby uses the account name');
await b.close();
